package generated_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/nnutter/constable/internal/generated"
)

func parse(t *testing.T, src string) *ast.File {
	t.Helper()

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "src.go", src, parser.ParseComments)
	require.NoError(t, err)

	return file
}

func TestIsGenerated(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{
			name: "standard comment before package clause",
			src:  "// Code generated by mockgen. DO NOT EDIT.\n\npackage p\n",
			want: true,
		},
		{
			name: "comment in a block with other comments",
			src:  "// Package doc.\n\n// Code generated by stringer. DO NOT EDIT.\n\npackage p\n",
			want: true,
		},
		{
			name: "no comment",
			src:  "package p\n",
			want: false,
		},
		{
			name: "comment without the marker",
			src:  "// Code generated by hand.\n\npackage p\n",
			want: false,
		},
		{
			name: "marker without the trailing period",
			src:  "// Code generated by hand. DO NOT EDIT\n\npackage p\n",
			want: false,
		},
		{
			name: "marker after the package clause",
			src:  "package p\n\n// Code generated by hand. DO NOT EDIT.\n",
			want: false,
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			assert.Equal(t, test.want, generated.IsGenerated(parse(t, test.src)))
		})
	}
}
